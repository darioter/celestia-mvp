-- Canasta: suma Día y ChangoMás (SKUs relevados 2026-11-10). Mismo seguimiento de los lunes que Jumbo y Carrefour.
create or replace function public.canasta_pedir() returns integer language plpgsql security definer set search_path to 'public', 'net' as $function$
declare r record; n int := 0; base text;
begin
  for r in select * from public.canasta_productos where activo loop
    base := case r.super when 'jumbo' then 'https://www.jumbo.com.ar' when 'carrefour' then 'https://www.carrefour.com.ar'
                         when 'dia' then 'https://diaonline.supermercadosdia.com.ar' when 'changomas' then 'https://www.masonline.com.ar' end;
    if base is null then continue; end if;
    insert into public.canasta_pedidos(request_id, super, clave, sku) values (net.http_get(base || '/api/catalog_system/pub/products/search?fq=skuId:' || r.sku), r.super, r.clave, r.sku);
    n := n + 1;
  end loop;
  return n;
end $function$;

