create or replace view public.canasta_indice as
 WITH base AS (
         SELECT DISTINCT ON (canasta_precios.super, canasta_precios.sku) canasta_precios.super, canasta_precios.sku, canasta_precios.precio
           FROM canasta_precios
          WHERE canasta_precios.clave NOT LIKE 'beb\_%'
          ORDER BY canasta_precios.super, canasta_precios.sku, canasta_precios.fecha
        ), rel AS (
         SELECT p.fecha, p.precio / b.precio AS r
           FROM canasta_precios p
             JOIN base b USING (super, sku)
          WHERE p.clave NOT LIKE 'beb\_%'
        )
 SELECT fecha, round(exp(avg(ln(r))), 4) AS indice, count(*) AS productos
   FROM rel
  WHERE r > 0.5 AND r < 2.5
  GROUP BY fecha
  ORDER BY fecha;
